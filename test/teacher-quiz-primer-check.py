"""Teacher quiz primer dropdown check.
Usage: BASE=http://localhost:8013/ SHOTS=/workspace/primer-dropdown python3 test/teacher-quiz-primer-check.py"""
import os, subprocess, tempfile, urllib.request
from playwright.sync_api import sync_playwright
BASE = os.environ.get('BASE', 'http://localhost:8013/').rstrip('/') + '/'
OUT = os.environ.get('SHOTS', '/workspace/primer-dropdown'); os.makedirs(OUT, exist_ok=True)
res = []
def check(n, c, x=''): res.append(bool(c)); print(('ok   ' if c else 'FAIL ') + n, '' if c else x)
with sync_playwright() as p:
    b = p.chromium.launch()
    def page(w, h, z=1):
        pg = b.new_page(viewport={'width': int(w / z), 'height': int(h / z)}, device_scale_factor=z)
        errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.goto(BASE + 'teacher-quiz.html?cb=' + str(os.getpid())); pg.wait_for_timeout(900)
        return pg, errs
    pg, errs = page(1280, 900)
    d = pg.locator('details#primer')
    check('primer: details element exists', d.count() == 1)
    check('primer: closed by default', not d.evaluate('e => e.open'))
    check('primer: title is "Primer for Ars Logica"', pg.inner_text('#primer summary').strip() == 'Primer for Ars Logica', pg.inner_text('#primer summary'))
    check('primer: placed above the level menu', pg.evaluate("() => !!(document.getElementById('primer').compareDocumentPosition(document.getElementById('diffSel')) & 4)"))
    pg.click('#primer summary'); pg.wait_for_timeout(200)
    check('primer: opens on click', d.evaluate('e => e.open'))
    a = pg.locator('#primerLink')
    check('link: target _blank, rel noopener', a.get_attribute('target') == '_blank' and 'noopener' in (a.get_attribute('rel') or ''))
    check('link: text', a.inner_text().strip() == 'Primers for all the exercises (PDF, 43 pages)', a.inner_text())
    href = a.evaluate('e => e.href')
    r = urllib.request.urlopen(urllib.request.Request(href, headers={'User-Agent': 'Mozilla/5.0'}))
    data = r.read()
    check('link: 200 application/pdf', r.status == 200 and r.headers.get('Content-Type', '').startswith('application/pdf'), (r.status, r.headers.get('Content-Type')))
    f = tempfile.NamedTemporaryFile(suffix='.pdf', delete=False); f.write(data); f.close()
    info = subprocess.run(['pdfinfo', f.name], capture_output=True, text=True).stdout; os.unlink(f.name)
    check('pdf: 43 pages', 'Pages:          43' in info or '\nPages: 43' in info.replace(' ', ' ') or any(l.split() == ['Pages:', '43'] for l in info.splitlines()), info)
    print('     pdf bytes:', len(data))
    text = pg.inner_text('#primer')
    check('primer: no AI mention', not any(w in text.lower() for w in (' ai ', 'artificial', 'chatgpt', 'generated by')))
    check('no page errors', not errs, errs)
    for w, z, tag in [(1280, 1, 'desktop'), (375, 1, 'phone'), (375, 2, 'phone-200')]:
        pg, errs = page(w, 800, z)
        pg.screenshot(path=f'{OUT}/primer-{tag}-closed.png')
        pg.click('#primer summary'); pg.wait_for_timeout(200)
        fit = pg.evaluate("""() => { const vw = document.documentElement.clientWidth;
          return document.documentElement.scrollWidth <= vw + 1 && [...document.querySelectorAll('#primer, #primer summary, #primer p, #primerLink')]
            .every(e => { const r = e.getBoundingClientRect(); return r.left >= -1 && r.right <= vw + 1; }); }""")
        check(f'{tag}: primer fits, no sideways scroll', fit)
        hgt = pg.evaluate("() => document.querySelector('#primer summary').getBoundingClientRect().height")
        check(f'{tag}: summary tap target at least 44px tall', hgt >= 44, hgt)
        pg.locator('#primer').screenshot(path=f'{OUT}/primer-{tag}-open.png')
        check(f'{tag}: no page errors', not errs, errs)
    pg, errs = page(1280, 900)
    pg.click('#selNone'); pg.locator('#setList input[type=checkbox]').first.check()
    for dv in range(1, 6):
        pg.select_option('#diffSel', str(dv)); pg.click('#genBtn'); pg.wait_for_timeout(500)
        n = pg.locator('#paper .q, #paper li, #paper ol > *').count()
        check(f'quiz generates at level {dv}', pg.inner_text('#paper').strip() != '' and n > 0, n)
    check('quiz generation: no page errors', not errs, errs)
    b.close()
print(f'\n{sum(res)}/{len(res)} passed'); raise SystemExit(0 if all(res) else 1)
